def main():
    da_co = get_known_words()
    # `not da_co`, KHÔNG `is None`: lúc Anki đang sync, AnkiConnect trả lỗi
    # "Collection lifecycle operation is active" và get_known_words() ra set() RỖNG
    # (đo 15/10) ⇒ tưởng chưa có thẻ nào, nạp lại cả danh sách.
    if not da_co:
        sys.exit("Không đọc được thẻ từ Anki (đang sync?) — DỪNG, thử lại sau ít phút.")
    da_co = da_co | {w.replace("ё", "е") for w in da_co}
    con = [t for t in DS if t[0] not in da_co and t[0].replace("ё", "е") not in da_co]
    con.sort(key=lambda t: -t[1])              # A2 trước, A1 sau cùng
    print(f"{len(DS)} từ trong danh sách, {len(con)} chưa có thẻ "
          f"(A1 {sum(t[1] == 1 for t in con)}, A2 {sum(t[1] == 2 for t in con)})")
    if "--thu" in sys.argv:
        chon = set(sys.argv[sys.argv.index("--thu") + 1:])
        con = [t for t in con if t[0] in chon]
    elif "--apply" not in sys.argv:
        return
    con = con[:TOI_DA]
    if not sync_truoc_khi_ghi_lo("nạp thô A1+A2"):
        sys.exit(1)
    hong, so_ok = [], 0
    for i, (tu, muc, nguon) in enumerate(con, 1):
        ok, info, err = process_word(tu, None)
        if ok and info.get("ai_degraded"):
            print(f"[{i}/{len(con)}] KHUYET {tu} — AI hụt (hết lượt Google?). DỪNG; "
                  f"thẻ này phải /sua lại.", flush=True)
            hong.append((tu, "thẻ KHUYẾT, cần /sua"))
            break
        if ok:
            so_ok += 1
            print(f"[{i}/{len(con)}] OK   {tu}", flush=True)
            continue
        if info and info.get("nhieu_muc"):
            err = "ĐỒNG TỰ: " + " | ".join(f"id={m['id']} {m['pos']} {m['en']}"
                                          for m in info["nhieu_muc"])
        hong.append((tu, err))
        print(f"[{i}/{len(con)}] HONG {tu}: {err}", flush=True)
    print(f"\nXONG lần này: {so_ok} ok, {len(hong)} hỏng — chạy lại khan để xem còn bao nhiêu")
    for tu, err in hong:
        print(f"  HONG {tu}: {err}")
    print("sync:", sync_now())


if __name__ == "__main__":
    main()
